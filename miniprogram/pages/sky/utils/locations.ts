const STORAGE_SAVED_LOCATIONS_KEY = 'sky_forecast_saved_locations';
const STORAGE_CURRENT_LOCATION_KEY = 'sky_forecast_current_location';

export function getSavedLocations(): LocationItem[] {
  try {
    const raw = wx.getStorageSync(STORAGE_SAVED_LOCATIONS_KEY);
    if (!raw) return [];
    if (typeof raw === 'string') {
      return JSON.parse(raw);
    }
    return raw;
  } catch {
    return [];
  }
}

export function saveLocation(loc: LocationItem): void {
  try {
    const list = getSavedLocations();
    const existsIndex = list.findIndex(
      (x) =>
        x.id === loc.id ||
        (Math.abs(x.latitude - loc.latitude) < 0.01 && Math.abs(x.longitude - loc.longitude) < 0.01)
    );
    if (existsIndex >= 0) {
      list[existsIndex] = loc;
    } else {
      list.unshift(loc);
    }
    wx.setStorageSync(STORAGE_SAVED_LOCATIONS_KEY, list);
  } catch (err) {
    console.warn('Failed to save location', err);
  }
}

export function removeSavedLocation(id: string): void {
  try {
    const list = getSavedLocations().filter((x) => x.id !== id);
    wx.setStorageSync(STORAGE_SAVED_LOCATIONS_KEY, list);
  } catch (err) {
    console.warn('Failed to remove location', err);
  }
}

export function getLastActiveLocation(): LocationItem {
  try {
    const raw = wx.getStorageSync(STORAGE_CURRENT_LOCATION_KEY);
    if (raw) {
      const parsed = typeof raw === 'string' ? JSON.parse(raw) : raw;
      if (parsed && parsed.latitude && parsed.longitude) {
        return parsed;
      }
    }
  } catch {
    // fallback
  }
  return PRESET_LOCATIONS[0]; // Default to 杭州宝石山
}

export function setLastActiveLocation(loc: LocationItem): void {
  try {
    wx.setStorageSync(STORAGE_CURRENT_LOCATION_KEY, loc);
  } catch (err) {
    console.warn('Failed to store active location', err);
  }
}
